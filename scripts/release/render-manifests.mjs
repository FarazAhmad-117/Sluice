#!/usr/bin/env node
/**
 * WRITES EVERY PACKAGE MANAGER'S MANIFEST FOR ONE CLI RELEASE.
 *
 *   node scripts/release/render-manifests.mjs [release dir] [out dir]
 *
 * Reads the version from packages/cli/package.json and each archive's
 * checksum from the release's SHA256SUMS (written by `build-binaries.mjs`),
 * and writes:
 *
 *   homebrew/sluice.rb             Formula/sluice.rb in FarazAhmad-117/homebrew-sluice
 *   scoop/sluice.json              bucket/sluice.json in FarazAhmad-117/scoop-sluice
 *   winget/Sluice.Sluice*.yaml     manifests/s/Sluice/Sluice/<version>/ in microsoft/winget-pkgs
 *
 * Every URL points at the GitHub release tagged `cli-v<version>`, so the
 * manifests are only valid once that release exists with these exact files.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const releaseDir = process.argv[2] ?? join(ROOT, "packages", "cli", "release");
const outDir = process.argv[3] ?? join(releaseDir, "manifests");

const { version, description, license } = JSON.parse(readFileSync(join(ROOT, "packages", "cli", "package.json"), "utf8"));
const REPO = "FarazAhmad-117/Sluice";
const HOMEPAGE = `https://github.com/${REPO}`;
const download = (file) => `https://github.com/${REPO}/releases/download/cli-v${version}/${file}`;

const sums = new Map(
  readFileSync(join(releaseDir, "SHA256SUMS"), "utf8")
    .trim()
    .split("\n")
    .map((line) => line.trim().split(/\s+/))
    .map(([sha, file]) => [file, sha]),
);
function sha(file) {
  const value = sums.get(file);
  if (!/^[0-9a-f]{64}$/.test(value ?? "")) throw new Error(`SHA256SUMS has no checksum for ${file}`);
  return value;
}

function write(path, text) {
  mkdirSync(dirname(join(outDir, path)), { recursive: true });
  writeFileSync(join(outDir, path), text);
  console.log(`wrote ${path}`);
}

// ---- Homebrew ---------------------------------------------------------------
const brewTarget = (os, arch) => {
  const file = `sluice-${os}-${arch}.tar.gz`;
  return `      url "${download(file)}"\n      sha256 "${sha(file)}"`;
};
write(
  "homebrew/sluice.rb",
  `# Generated by scripts/release/render-manifests.mjs for cli-v${version}. Do not edit by hand.
class Sluice < Formula
  desc "${description.replace(/\.$/, "").replace(/"/g, '\\"')}"
  homepage "${HOMEPAGE}"
  version "${version}"
  license "${license}"

  on_macos do
    on_arm do
${brewTarget("darwin", "arm64")}
    end
    on_intel do
${brewTarget("darwin", "x64")}
    end
  end

  on_linux do
    on_arm do
${brewTarget("linux", "arm64")}
    end
    on_intel do
${brewTarget("linux", "x64")}
    end
  end

  def install
    bin.install "sluice"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/sluice --version")
  end
end
`,
);

// ---- Scoop ------------------------------------------------------------------
write(
  "scoop/sluice.json",
  `${JSON.stringify(
    {
      version,
      description,
      homepage: HOMEPAGE,
      license,
      architecture: {
        "64bit": { url: download("sluice-windows-x64.zip"), hash: sha("sluice-windows-x64.zip") },
      },
      bin: "sluice.exe",
      checkver: {
        url: `https://api.github.com/repos/${REPO}/releases/latest`,
        jsonpath: "$.tag_name",
        regex: "cli-v([\\d.]+)",
      },
      autoupdate: {
        architecture: {
          "64bit": { url: `https://github.com/${REPO}/releases/download/cli-v$version/sluice-windows-x64.zip` },
        },
        hash: { url: "$baseurl/SHA256SUMS" },
      },
    },
    null,
    2,
  )}\n`,
);

// ---- winget -----------------------------------------------------------------
const ID = "Sluice.Sluice";
const MANIFEST_VERSION = "1.6.0";
const header = (schema) =>
  `# Generated by scripts/release/render-manifests.mjs for cli-v${version}.\n# yaml-language-server: $schema=https://aka.ms/winget-manifest.${schema}.${MANIFEST_VERSION}.schema.json\n\n`;

write(
  `winget/${ID}.yaml`,
  `${header("version")}PackageIdentifier: ${ID}
PackageVersion: ${version}
DefaultLocale: en-US
ManifestType: version
ManifestVersion: ${MANIFEST_VERSION}
`,
);
write(
  `winget/${ID}.installer.yaml`,
  `${header("installer")}PackageIdentifier: ${ID}
PackageVersion: ${version}
InstallerType: zip
NestedInstallerType: portable
NestedInstallerFiles:
- RelativeFilePath: sluice.exe
  PortableCommandAlias: sluice
Installers:
- Architecture: x64
  InstallerUrl: ${download("sluice-windows-x64.zip")}
  InstallerSha256: ${sha("sluice-windows-x64.zip").toUpperCase()}
ManifestType: installer
ManifestVersion: ${MANIFEST_VERSION}
`,
);
write(
  `winget/${ID}.locale.en-US.yaml`,
  `${header("defaultLocale")}PackageIdentifier: ${ID}
PackageVersion: ${version}
PackageLocale: en-US
Publisher: Sluice
PublisherUrl: ${HOMEPAGE}
PublisherSupportUrl: ${HOMEPAGE}/issues
PackageName: Sluice
PackageUrl: ${HOMEPAGE}
License: ${license}
LicenseUrl: ${HOMEPAGE}/blob/HEAD/LICENSE
ShortDescription: ${description}
Description: Runs any command with secrets from Sluice, decrypted on your machine, with no .env file on disk, and stops it within seconds when its token is revoked.
Moniker: sluice
Tags:
- secrets
- dotenv
- environment-variables
- cli
- security
ManifestType: defaultLocale
ManifestVersion: ${MANIFEST_VERSION}
`,
);
